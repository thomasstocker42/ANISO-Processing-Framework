#!/usr/bin/env python3
"""
APF CHI03b: MEDI susceptibility source separation orchestration.

Version 0.2.0

Purpose
-------
Prepare, preflight, and summarize production chi-separation reconstruction
using the official SNU-LIST chi_sep_MEDI implementation.

The numerical reconstruction itself is performed by:

    scripts/chiseparation/chi03b_medi_runner.m

inside the validated MATLAB R2026a container. This Python module deliberately
does not reimplement the MATLAB solver.

Inputs
------
CHI02 solver package:
    localfield.nii.gz
    r2prime.nii.gz
    magnitude.nii.gz
    mask.nii.gz
    params.json

Additional frozen CHI03b inputs:
    GRE02 phase:
        gre02_<CASE>_phase_rad_4d.nii.gz

    R2STAR02:
        r2star02_<CASE>_r2star_s-1.nii.gz

    GRE06c STI-iLSQR QSM:
        <CASE>_GRE06c_sti_ilsqr_chi_ppm.nii.gz

Scientific policy
-----------------
- CHI02 remains frozen and unchanged.
- Raw R2-prime is retained unchanged upstream.
- At the MEDI solver boundary only:
      non-finite R2-prime -> 0
      negative R2-prime   -> 0
      then solver mask is applied
- MEDI parameters are frozen to:
      Dr = 137 Hz/ppm
      lambda = 1
      lambda_CSF = 1
- Noise weighting is generated by official Preprocessing4Phase.
- CSF support is generated by MEDI extract_CSF and intersected with the
  production solver mask.
- External QSM is the frozen GRE06c STI-iLSQR reconstruction.

Execution model
---------------
This script performs host-side APF orchestration. MATLAB execution is kept
inside an already authenticated MATLAB container to avoid repeated online
licensing/authentication.

Default mode:
    preflight selected cases, prepare output directories, and generate a
    MATLAB command file.

--collect:
    validate completed case outputs and generate cohort CSV/JSON summaries.
"""

from __future__ import annotations

import argparse
import csv
import grp
import json
import os
import platform
import sys
from datetime import datetime
from pathlib import Path
from typing import Any

from apf_paths import APFPaths, get_paths
from apf_case_selection import (
    add_case_selection_args,
    print_selected_cases,
    resolve_cases,
)


SCRIPT = "03b_medi.py"
SCRIPT_ID = "CHI03b"
TAG = "chi03b"
VERSION = "0.2.0"

MATLAB_RUNNER = "chi03b_medi_runner.m"

SNU_LIST_VERSION = "1.2.2"
MEDI_GIT_COMMIT = "83c19607a50b25cf28838469ede60e54aa636183"
MATLAB_IMAGE = "matlab-r2026a-chisep:latest"
MATLAB_IMAGE_ID = (
    "sha256:"
    "661a912e3173055c2e20ccd984c4a8ac491fdd1f2bfd96620761502401963464"
)

DR_HZ_PER_PPM = 137.0
LAMBDA = 1.0
LAMBDA_CSF = 1.0

OUTPUT_GROUP = "users"
OUTPUT_MODE = 0o2775


def now_iso() -> str:
    return datetime.now().isoformat(timespec="seconds")


def require_file(path: Path, label: str) -> Path:
    if not path.is_file():
        raise FileNotFoundError(f"Missing {label}: {path}")
    return path


def case_paths(
    paths: APFPaths,
    case: str,
) -> dict[str, Path]:
    chi02 = (
        paths.derivatives_dir
        / case
        / "chi_separation"
        / "chi02_prepare"
        / "qsm_ci_input"
    )

    gre = paths.derivatives_dir / case / "GRE"

    return {
        "chi02_localfield": chi02 / "localfield.nii.gz",
        "chi02_r2prime": chi02 / "r2prime.nii.gz",
        "chi02_magnitude": chi02 / "magnitude.nii.gz",
        "chi02_mask": chi02 / "mask.nii.gz",
        "chi02_params": chi02 / "params.json",
        "phase_4d": (
            gre
            / "phase_preparation_gre02"
            / f"gre02_{case}_phase_rad_4d.nii.gz"
        ),
        "r2star": (
            paths.derivatives_dir
            / case
            / "relaxometry"
            / "r2star"
            / "r2star02_loglinear"
            / f"r2star02_{case}_r2star_s-1.nii.gz"
        ),
        "qsm": (
            gre
            / "06c_sti_ilsqr"
            / f"{case}_GRE06c_sti_ilsqr_chi_ppm.nii.gz"
        ),
    }


def output_dir(
    paths: APFPaths,
    case: str,
) -> Path:
    return (
        paths.derivatives_dir
        / case
        / "chi_separation"
        / "chi03b_medi"
    )


def cohort_output_dir(
    paths: APFPaths,
) -> Path:
    return (
        paths.derivatives_dir
        / "summary"
        / "chi_separation"
        / "chi03b_medi"
    )


def expected_outputs(
    paths: APFPaths,
    case: str,
) -> dict[str, Path]:
    out = output_dir(paths, case)

    return {
        "chi_para": out / f"chi03b_{case}_chi_para_ppm.nii.gz",
        "chi_dia": out / f"chi03b_{case}_chi_dia_ppm.nii.gz",
        "chi_tot": out / f"chi03b_{case}_chi_tot_ppm.nii.gz",
        "mask_csf": out / f"chi03b_{case}_mask_CSF.nii.gz",
        "qc_json": out / f"chi03b_{case}_qc.json",
    }


def prepare_shared_directory(path: Path) -> None:
    """
    Create a host/container shared output directory.

    MATLAB container user is a member of group 'users'. The setgid bit makes
    files/directories created below this directory inherit that group.
    """
    path.mkdir(
        parents=True,
        exist_ok=True,
    )

    group = grp.getgrnam(OUTPUT_GROUP)

    try:
        os.chown(
            path,
            -1,
            group.gr_gid,
        )
    except PermissionError as exc:
        raise PermissionError(
            f"Could not change group of {path} to {OUTPUT_GROUP}. "
            "The directory must be owned by the host user."
        ) from exc

    os.chmod(
        path,
        OUTPUT_MODE,
    )


def preflight_case(
    paths: APFPaths,
    case: str,
) -> dict[str, Any]:
    inp = case_paths(
        paths,
        case,
    )

    missing: list[str] = []

    for label, path in inp.items():
        if not path.is_file():
            missing.append(
                f"{label}: {path}"
            )

    status = (
        "READY"
        if not missing
        else "MISSING_INPUT"
    )

    return {
        "case_id": case,
        "status": status,
        "missing": missing,
        "inputs": {
            key: str(value)
            for key, value in inp.items()
        },
        "output_dir": str(
            output_dir(
                paths,
                case,
            )
        ),
    }


def write_case_manifest(
    paths: APFPaths,
    case: str,
    preflight: dict[str, Any],
) -> Path:
    out = output_dir(
        paths,
        case,
    )

    manifest = {
        "script": SCRIPT,
        "script_id": SCRIPT_ID,
        "version": VERSION,
        "generated_at": now_iso(),
        "case_id": case,
        "preflight_status": preflight["status"],
        "inputs": preflight["inputs"],
        "output_dir": str(out),
        "solver": {
            "method": "chi_sep_MEDI",
            "snu_list_version": SNU_LIST_VERSION,
            "medi_git_commit": MEDI_GIT_COMMIT,
            "matlab_image": MATLAB_IMAGE,
            "matlab_image_id": MATLAB_IMAGE_ID,
            "Dr_Hz_per_ppm": DR_HZ_PER_PPM,
            "lambda": LAMBDA,
            "lambda_CSF": LAMBDA_CSF,
            "CSF_extraction": "MEDI extract_CSF",
            "CSF_flag_erode": 0,
            "CSF_thresh_R2s_per_s": 5,
        },
        "r2prime_solver_boundary_policy": {
            "upstream_raw_preserved": True,
            "nonfinite_to_zero": True,
            "negative_to_zero": True,
            "mask_applied_after_sanitization": True,
        },
        "additional_inputs_beyond_CHI02": {
            "gre02_phase_4d": True,
            "r2star02_for_extract_CSF": True,
            "gre06c_sti_ilsqr_qsm": True,
        },
        "execution": {
            "matlab_runner": (
                "scripts/chiseparation/"
                + MATLAB_RUNNER
            ),
            "container_execution_manual": True,
        },
    }

    path = (
        out
        / f"chi03b_{case}_manifest.json"
    )

    path.write_text(
        json.dumps(
            manifest,
            indent=2,
        )
        + "\n"
    )

    return path


def matlab_command(
    case: str,
) -> str:
    return (
        "chi03b_medi_runner("
        f"'{case}'"
        ");"
    )


def write_matlab_batch_file(
    paths: APFPaths,
    cases: list[str],
) -> Path:
    cohort = cohort_output_dir(
        paths,
    )

    cohort.mkdir(
        parents=True,
        exist_ok=True,
    )

    path = (
        cohort
        / "chi03b_medi_batch_commands.m"
    )

    lines = [
        "% APF CHI03b MEDI production batch",
        f"% Generated: {now_iso()}",
        "%",
        "% Run inside the validated MATLAB container after:",
        "%   addpath('/project/scripts/chiseparation');",
        "",
    ]

    for case in cases:
        log_path = (
            f"/project/derivatives/{case}/chi_separation/"
            f"chi03b_medi/chi03b_{case}_matlab.log"
        )

        lines.extend(
            [
                f"fprintf('\\n===== CHI03b {case} =====\\n');",
                f"diary('{log_path}');",
                "try",
                f"    {matlab_command(case)}",
                "catch ME",
                f"    fprintf(2, 'CHI03b FAILED: {case}\\n');",
                "    disp(getReport(ME, 'extended', 'hyperlinks', 'off'));",
                "end",
                "diary off;",
                "",
            ]
        )

    path.write_text(
        "\n".join(lines)
        + "\n"
    )

    return path


def scalar(
    data: dict[str, Any],
    key: str,
) -> Any:
    return data.get(
        key,
        "",
    )


def collect_case(
    paths: APFPaths,
    case: str,
) -> dict[str, Any]:
    out = expected_outputs(
        paths,
        case,
    )

    missing = [
        str(path)
        for path in out.values()
        if not path.is_file()
    ]

    if missing:
        return {
            "case_id": case,
            "status": "INCOMPLETE",
            "missing_outputs": missing,
        }

    qc = json.loads(
        out["qc_json"].read_text()
    )

    if qc.get("status") != "COMPLETED":
        return {
            "case_id": case,
            "status": "QC_NOT_COMPLETED",
            "qc_status": qc.get("status"),
        }

    return {
        "case_id": case,
        "status": "COMPLETED",
        "runtime_seconds": scalar(
            qc,
            "runtime_seconds",
        ),
        "mask_voxels": scalar(
            qc,
            "mask_voxels",
        ),
        "csf_voxels": scalar(
            qc,
            "csf_voxels",
        ),
        "r2prime_nonfinite_raw_whole_volume": scalar(
            qc,
            "r2prime_nonfinite_raw_whole_volume",
        ),
        "r2prime_nonfinite_raw_in_mask": scalar(
            qc,
            "r2prime_nonfinite_raw_in_mask",
        ),
        "r2prime_negative_voxels_in_mask": scalar(
            qc,
            "r2prime_negative_voxels_in_mask",
        ),
        "algebra_rmse_ppm": scalar(
            qc,
            "algebra_rmse_ppm",
        ),
        "qsm_rmse_ppm": scalar(
            qc,
            "qsm_rmse_ppm",
        ),
        "qsm_pearson_r": scalar(
            qc,
            "qsm_pearson_r",
        ),
        "para_dia_pearson_r": scalar(
            qc,
            "para_dia_pearson_r",
        ),
        "qc_json": str(
            out["qc_json"]
        ),
    }


def write_cohort_summary(
    paths: APFPaths,
    rows: list[dict[str, Any]],
) -> tuple[Path, Path]:
    cohort = cohort_output_dir(
        paths,
    )

    cohort.mkdir(
        parents=True,
        exist_ok=True,
    )

    csv_path = (
        cohort
        / "chi03b_medi_cohort_summary.csv"
    )

    json_path = (
        cohort
        / "chi03b_medi_cohort_summary.json"
    )

    fieldnames = [
        "case_id",
        "status",
        "runtime_seconds",
        "mask_voxels",
        "csf_voxels",
        "r2prime_nonfinite_raw_whole_volume",
        "r2prime_nonfinite_raw_in_mask",
        "r2prime_negative_voxels_in_mask",
        "algebra_rmse_ppm",
        "qsm_rmse_ppm",
        "qsm_pearson_r",
        "para_dia_pearson_r",
        "qc_json",
        "missing_outputs",
        "qc_status",
    ]

    with csv_path.open(
        "w",
        newline="",
    ) as f:
        writer = csv.DictWriter(
            f,
            fieldnames=fieldnames,
            extrasaction="ignore",
        )
        writer.writeheader()

        for row in rows:
            clean = dict(row)

            if isinstance(
                clean.get("missing_outputs"),
                list,
            ):
                clean["missing_outputs"] = "; ".join(
                    clean["missing_outputs"]
                )

            writer.writerow(clean)

    payload = {
        "script": SCRIPT,
        "script_id": SCRIPT_ID,
        "version": VERSION,
        "generated_at": now_iso(),
        "host": platform.node(),
        "python": sys.version.split()[0],
        "n_cases": len(rows),
        "n_completed": sum(
            row.get("status") == "COMPLETED"
            for row in rows
        ),
        "rows": rows,
    }

    json_path.write_text(
        json.dumps(
            payload,
            indent=2,
        )
        + "\n"
    )

    return (
        csv_path,
        json_path,
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=(
            "APF CHI03b MEDI orchestration "
            "and cohort QC collection."
        )
    )

    add_case_selection_args(parser)

    parser.add_argument(
        "--collect",
        action="store_true",
        help=(
            "Collect completed MATLAB outputs and "
            "write cohort CSV/JSON summaries."
        ),
    )

    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()

    paths = get_paths()

    cases = resolve_cases(
        args,
        paths.ins_registry,
    )

    print_selected_cases(cases)

    if args.collect:
        rows = [
            collect_case(
                paths,
                case,
            )
            for case in cases
        ]

        csv_path, json_path = (
            write_cohort_summary(
                paths,
                rows,
            )
        )

        print()
        print("CHI03b collection:")
        for row in rows:
            print(
                f"  {row['case_id']}: "
                f"{row['status']}"
            )

        print()
        print(
            f"Cohort CSV:  {csv_path}"
        )
        print(
            f"Cohort JSON: {json_path}"
        )

        n_bad = sum(
            row["status"] != "COMPLETED"
            for row in rows
        )

        return 1 if n_bad else 0

    preflight_rows: list[dict[str, Any]] = []
    ready_cases: list[str] = []

    for case in cases:
        row = preflight_case(
            paths,
            case,
        )

        preflight_rows.append(row)

        if row["status"] != "READY":
            print()
            print(
                f"[MISSING_INPUT] {case}"
            )

            for item in row["missing"]:
                print(
                    f"  {item}"
                )

            continue

        out = output_dir(
            paths,
            case,
        )

        prepare_shared_directory(out)

        manifest = write_case_manifest(
            paths,
            case,
            row,
        )

        ready_cases.append(case)

        print(
            f"[READY] {case}"
        )
        print(
            f"  output:   {out}"
        )
        print(
            f"  manifest: {manifest}"
        )

    cohort = cohort_output_dir(
        paths,
    )
    cohort.mkdir(
        parents=True,
        exist_ok=True,
    )

    preflight_json = (
        cohort
        / "chi03b_medi_preflight.json"
    )

    preflight_json.write_text(
        json.dumps(
            {
                "script": SCRIPT,
                "script_id": SCRIPT_ID,
                "version": VERSION,
                "generated_at": now_iso(),
                "rows": preflight_rows,
            },
            indent=2,
        )
        + "\n"
    )

    batch_file = write_matlab_batch_file(
        paths,
        ready_cases,
    )

    print()
    print(
        f"Ready: {len(ready_cases)}/{len(cases)}"
    )
    print(
        f"Preflight: {preflight_json}"
    )
    print(
        f"MATLAB batch file: {batch_file}"
    )

    if ready_cases:
        print()
        print(
            "Inside the authenticated MATLAB "
            "container run:"
        )
        print(
            "  addpath('/project/scripts/chiseparation');"
        )
        print(
            "  run('/project/"
            + str(
                batch_file.relative_to(
                    paths.root
                )
            )
            + "');"
        )

    return (
        0
        if len(ready_cases) == len(cases)
        else 1
    )


if __name__ == "__main__":
    raise SystemExit(main())
